#!/usr/bin/env python3
"""Generate frontend/config.js (addresses, ABIs, chain id, RPC URL, demo accounts) from a deployment file.

Usage:
  gen_config.py --deployment contracts/deployments/31337.json --rpc-url http://127.0.0.1:8554 [--out frontend/config.js]
For a public testnet pass that chain's deployment file and a browser-reachable RPC URL; demo (unlocked) accounts are
only emitted for the local anvil chain (31337).
"""

from __future__ import annotations

import argparse
import json
import os
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "contracts", "out")

DEMO_ACCOUNTS = [
    ("Alice", "0xf39Fd6e51aad88F6F4ce6aB8827279cffFb92266", "Admin · market creator · LP"),
    ("Bob", "0x70997970C51812dc3A010C7d01b50e0d17dc79C8", "Trader"),
    ("Carol", "0x3C44CdDdB6a900fa2b585dd299e03d12FA4293BC", "Trader · P2P market maker"),
    ("Dave", "0x90F79bf6EB2c4f870365E785982E1f101E93b906", "Arbitrator"),
    ("Eve", "0x15d34AAf54267DB7D7c367839AAf71A00a2C6A65", "Reporter"),
    ("Frank", "0x9965507D1a55bcC2695C58ba16FB37d819B0A4dc", "Reporter · trader"),
    ("Grace", "0x976EA74026E726554dB657fA54763abd0C3a0aa9", "Reporter · trader"),
    ("Heidi", "0x14dC79964da2C08b23698B3D3cc7Ca32193d9955", "Reporter"),
    ("Ivan", "0x23618e81E3f5cdF7f54C3d65f7FBc0aBf5B21E8f", "Trader · LP · absent arbitrator"),
    ("Judy", "0xa0Ee7A142d267C1f36714E4a8F75612F20a79720", "New user (no tokens yet)"),
]


def abi(source: str, name: str) -> list:
    with open(os.path.join(OUT_DIR, f"{source}.sol", f"{name}.json")) as f:
        return json.load(f)["abi"]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--deployment", required=True)
    ap.add_argument("--rpc-url", required=True)
    ap.add_argument("--chain-name", default=None)
    ap.add_argument("--out", default=os.path.join(ROOT, "frontend", "config.js"))
    args = ap.parse_args()

    with open(args.deployment) as f:
        dep = json.load(f)
    chain_id = int(dep["chainId"])
    local = chain_id == 31337

    config = {
        "chainId": chain_id,
        "chainName": args.chain_name or ("Anvil (local)" if local else f"Chain {chain_id}"),
        "rpcUrl": args.rpc_url,
        "startBlock": int(dep.get("startBlock", 0)),
        "generatedAt": int(time.time()),
        "contracts": {
            "PredictionMarket": {"address": dep["PredictionMarket"], "abi": abi("PredictionMarket", "PredictionMarket")},
            "OrderBook": {"address": dep["OrderBook"], "abi": abi("OrderBook", "OrderBook")},
            "ReputationOracle": {"address": dep["ReputationOracle"], "abi": abi("ReputationOracle", "ReputationOracle")},
        },
        "tokens": [
            {"symbol": "USDT", "name": "Tether USD (mock, 6 decimals)", "address": dep["USDT"], "decimals": 6,
             "kind": "faucet", "abi": abi("MockUSDT", "MockUSDT")},
            {"symbol": "DAI", "name": "Dai Stablecoin (mock, 18 decimals)", "address": dep["DAI"], "decimals": 18,
             "kind": "faucet", "abi": abi("MockERC20", "MockERC20")},
            {"symbol": "WETH", "name": "Wrapped Ether (18 decimals)", "address": dep["WETH"], "decimals": 18,
             "kind": "weth", "abi": abi("WETH9", "WETH9")},
        ],
        "demoAccounts": [{"name": n, "address": a, "role": r} for n, a, r in DEMO_ACCOUNTS] if local else [],
    }
    with open(args.out, "w") as f:
        f.write("// Generated by scripts/gen_config.py -- do not edit by hand.\n")
        f.write("window.APP_CONFIG = ")
        json.dump(config, f, separators=(",", ":"))
        f.write(";\n")
    print(f"gen_config: wrote {os.path.relpath(args.out, ROOT)} (chainId {chain_id}, rpc {args.rpc_url})")


if __name__ == "__main__":
    main()
